"""
Generate `lib/reports/helvetica-metrics.ts`.

The widths of Helvetica and Helvetica-Bold are not ours to invent: they are
part of the PostScript standard-14 set that every PDF reader carries, which is
exactly why the report writer can use those two fonts without embedding a font
programme at all. The numbers come from reportlab's copy of the Adobe AFM
metrics, indexed by WinAnsi code point so the writer can measure a string it
is about to encode.

Run: python3 -I scripts/gen-font-metrics.py
"""

from reportlab.pdfbase._fontdata_widths_helvetica import widths as regular
from reportlab.pdfbase._fontdata_widths_helveticabold import widths as bold
from reportlab.pdfbase._fontdata_enc_winansi import WinAnsiEncoding as winansi

HEADER = '''/**
 * Helvetica and Helvetica-Bold advance widths, in 1/1000 em, by WinAnsi code.
 *
 * GENERATED by `scripts/gen-font-metrics.py`. Do not edit by hand.
 *
 * ## Why these numbers exist at all
 *
 * The report writer measures every string before it draws it — to fit a column,
 * to right-align a figure, to truncate a long client name at a character
 * boundary rather than mid-glyph. Measuring needs the font's advance widths,
 * and these two fonts are the one case where a PDF can have them without
 * carrying a font file: Helvetica and Helvetica-Bold are two of the fourteen
 * standard faces every conforming reader already has, which is why the
 * generated documents are tens of kilobytes rather than megabytes.
 *
 * The values are Adobe's own AFM metrics, taken from reportlab's copy of them
 * and indexed by WinAnsi code point, which is the encoding the writer declares.
 * A code with no glyph in the encoding is 0 and is never emitted: the writer
 * substitutes before it measures.
 */

'''


def table(widths: dict[str, int]) -> str:
    rows = []
    for code in range(256):
        name = winansi[code]
        rows.append(widths.get(name, 0) if name else 0)

    lines = []
    for start in range(0, 256, 16):
        chunk = ', '.join(str(value) for value in rows[start : start + 16])
        lines.append(f'  {chunk},')
    return '\n'.join(lines)


with open('lib/reports/helvetica-metrics.ts', 'w', encoding='utf-8') as out:
    out.write(HEADER)
    out.write('/** Helvetica, by WinAnsi code point. */\n')
    out.write('export const HELVETICA_WIDTHS: readonly number[] = [\n')
    out.write(table(regular))
    out.write('\n];\n\n')
    out.write('/** Helvetica-Bold, by WinAnsi code point. */\n')
    out.write('export const HELVETICA_BOLD_WIDTHS: readonly number[] = [\n')
    out.write(table(bold))
    out.write('\n];\n')

print('wrote lib/reports/helvetica-metrics.ts')
