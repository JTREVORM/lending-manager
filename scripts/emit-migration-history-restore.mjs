#!/usr/bin/env node
// Emits the exact SQL that restores the nine pre-rename migration-history rows
// removed by scripts/sql/migration-history-repair.sql.
//
// Offline: reads only the verified audit artifact. No database, no psql, no
// network. It prints SQL to stdout and executes nothing.
//
//   node scripts/emit-migration-history-restore.mjs > restore.sql
//
// Every record is re-hashed against the manifest before it is emitted, so the
// generator refuses to produce a restore script from a tampered artifact.

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const artifact =
  process.argv[2] ?? join(root, 'docs/audit/polytos-migration-history-2026-11-01');
const manifest = JSON.parse(readFileSync(join(artifact, 'manifest.json'), 'utf8'));

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

// A dollar-quote tag that cannot occur in the body. The migrations themselves
// use $$, so a bare $$ would terminate the literal early and corrupt the SQL.
const quote = (version, sql) => {
  let tag = `restore_${version}`;
  while (sql.includes(`$${tag}$`)) tag += '_x';
  return `$${tag}$${sql}$${tag}$`;
};

const values = manifest.records.map((record) => {
  const sql = readFileSync(join(artifact, record.file));
  const actual = sha256(sql);
  if (actual !== record.sha256) {
    throw new Error(
      `${record.file} hashes ${actual} but the manifest says ${record.sha256}. ` +
        'Refusing to emit a restore script from an artifact that does not verify.',
    );
  }
  const createdBy = record.created_by
    ? `'${record.created_by.replace(/'/g, "''")}'`
    : 'null';
  return (
    `  ('${record.version}', '${record.name}', ${createdBy}, null, null,\n` +
    `   array[${quote(record.version, sql.toString('utf8'))}]::text[])`
  );
});

process.stdout
  .write(`-- POLYTOS migration-history restore - REVERSES THE AUTHORIZED REPAIR
--
-- Generated by scripts/emit-migration-history-restore.mjs from
-- ${manifest.records.length} verified records in the audit artifact
-- (captured ${manifest.captured_at_utc} from project ${manifest.project_ref}).
--
-- Puts the nine pre-rename rows back exactly as they were: same versions, same
-- names, same created_by, same single-element statements array, rollback and
-- idempotency_key null. ON CONFLICT DO NOTHING makes it safe to re-run and
-- means it will never overwrite a row that already exists.
--
-- Requires explicit authorization, like the repair it reverses.

insert into supabase_migrations.schema_migrations
  (version, name, created_by, idempotency_key, rollback, statements)
values
${values.join(',\n')}
on conflict (version) do nothing
returning version, name;
`);
